// GuiNotify.h — 从服务进程向界面（Electron 主进程）发一条"请退出"的通知。
//
// 为什么要单独一个文件：这条通知只依赖一个管道名和 Win32，没有别的业务
// 依赖（不碰状态文件、不碰托盘、不碰会话）。托盘「退出」要用它，将来别的
// 退出入口（比如命令行停服务时也想顺手关界面）也能直接复用；出问题时可以
// 单独写个小程序调一次，不用把整个服务跑起来。
#pragma once

namespace shadow {

/**
 * 请界面退出。界面没在运行（管道不存在）时返回 false。
 *
 * 两条通道，管道优先：
 *   1. 命名管道 \\.\pipe\ShadowPlay.Gui.v1（界面监听，最干净、零延迟）；
 *   2. 管道连不上时写一个标记文件 status/gui-quit-requested，界面每秒轮询
 *      状态时看到就把自己关掉。
 *
 * 为什么需要第 2 条：管道的访问检查跟着**进程完整性级别**走。服务要是被
 * "以管理员身份运行"（High），去连普通权限界面（Medium）建的管道会吃
 * ERROR_ACCESS_DENIED —— 界面明明开着却收不到通知。标记文件没有这个问题，
 * 代价只是最多慢 1 秒。
 *
 * 内部最多等约 400ms（界面正在启动/处理上一条命令时会短暂 ERROR_PIPE_BUSY），
 * 调用方可以是托盘线程。
 *
 * @param reason 传给界面的原因字符串（界面上只用于日志）。
 * @return 是否至少有一条通道送到。
 */
bool NotifyGuiShutdown(const char* reason);

} // namespace shadow
