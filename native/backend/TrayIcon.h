#pragma once

// ---------------------------------------------------------------------------
// TrayIcon —— 采集服务的系统托盘图标（Windows 通知区域）。
//
// 【为什么挂在服务进程上，而不是 Electron】
// 用户要求「Electron 退出，服务也不能退出」。如果托盘在 Electron 里，Electron
// 一关托盘就没了，服务倒是在跑，却没了唯一的常驻入口。所以托盘必须由服务自己
// 画 —— 服务在，托盘就在；Electron 关了托盘照样在。
//
// 右键菜单只有两项，简单直接：
//   · 打开主界面  —— 把 Electron 界面重新拉起来（服务一直活着，等价于「回到 App」）
//   · 退出        —— 干净地停掉**整套**（服务 + 守护），见下方说明
//
// 【退出为什么不是「直接杀自己」】
// 服务有守护看着：杀了服务，守护 2 秒内又把它拉起来，等于没退。所以退出要走
// 「停机哨兵」：先在状态目录写 `shutdown-requested`，守护下一轮巡检看到它就
// 自己退出、且不再拉服务；服务这边把 g_running 置 false，主循环几十毫秒内收尾
// 退出。两边读到同一个哨兵，谁先谁后都能干净收场。
//
// 托盘跑在独立线程的消息循环里（服务主线程忙着抓帧），互不干扰。
// ---------------------------------------------------------------------------

#include <string>

namespace shadow {

/**
 * 启动托盘图标（开一条后台线程跑消息循环）。
 *
 * @param profilesPath  服务用的配置文件绝对路径（用来推导项目根目录，给
 *                      「打开主界面」当 cwd 用）。
 */
void StartTrayIcon(const std::string& profilesPath);

/**
 * 请求服务退出（托盘「退出」按钮和可能的外部调用方用）。
 *
 * 不是直接杀进程：先写停机哨兵（让守护别再把服务拉起来），再把 g_running 置
 * false 并唤醒主循环，主循环几十毫秒内收尾退出去。
 */
void RequestServiceExit();

} // namespace shadow
